#!/usr/bin/env python3
"""Generate tokens/tokens.css from tokens/tokens.json and check WCAG contrast.

Usage:
  python3 build/tokens.py            # check contrast, then write tokens.css
  python3 build/tokens.py --check    # check only; exit 1 on failure (for CI)

No dependencies beyond the standard library.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tokens" / "tokens.json"
OUT = ROOT / "tokens" / "tokens.css"
META_KEYS = {"label", "scheme"}


def luminance(hex_color: str) -> float:
    h = hex_color.lstrip("#")[:6]
    channels = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def ratio(a: str, b: str) -> float:
    la, lb = sorted([luminance(a), luminance(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)


def check(spec: dict) -> bool:
    c = spec["contrast"]
    ok = True
    for name, theme in spec["themes"].items():
        print(f"\n[{name}]")
        for tok in c["text_tokens"]:
            cells = []
            for bg in c["required_on"] + c["reported_on"]:
                r = ratio(theme[tok], theme[bg])
                required = bg in c["required_on"]
                flag = ""
                if r < c["min_ratio"]:
                    flag = " FAIL" if required else " (low)"
                    ok = ok and not required
                cells.append(f"{bg.removeprefix('bg-')} {r:5.2f}{flag}")
            print(f"  {tok:16} {theme[tok]}  " + "  ".join(cells))
    print("\ncontrast:", "PASS" if ok else "FAIL")
    return ok


def theme_block(selector: str, theme: dict) -> str:
    lines = [f"{selector} {{", f"  color-scheme: {theme['scheme']};"]
    lines += [f"  --vg-{k}: {v};" for k, v in theme.items() if k not in META_KEYS]
    lines.append("}")
    return "\n".join(lines)


def render(spec: dict) -> str:
    default = spec["default_theme"]
    parts = [
        f"/* verdigris design tokens v{spec['version']}. GENERATED by build/tokens.py from tokens.json. Do not edit by hand. */",
        "/* Themes: set data-theme on <html>. Default (no attribute) is "
        f"'{default}'. Values: {', '.join(spec['themes'])}. */",
        "",
        ":root {\n" + "\n".join(f"  --vg-{k}: {v};" for k, v in spec["scale"].items()) + "\n}",
        "",
        theme_block(f':root, [data-theme="{default}"]', spec["themes"][default]),
    ]
    for name, theme in spec["themes"].items():
        if name != default:
            parts += ["", theme_block(f'[data-theme="{name}"]', theme)]
    return "\n".join(parts) + "\n"


def main() -> int:
    spec = json.loads(SRC.read_text())
    ok = check(spec)
    if "--check" in sys.argv:
        return 0 if ok else 1
    if not ok:
        print("not writing tokens.css: fix contrast failures first", file=sys.stderr)
        return 1
    OUT.write_text(render(spec))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
